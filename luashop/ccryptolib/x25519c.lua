local
expect=require"cc.expect".expect
local
lassert=require"ccryptolib.internal.util".lassert
local
hw=require"ccryptolib.internal.hw"local
fq=require"ccryptolib.internal.fq"local
fp=require"ccryptolib.internal.fp"local
c25=require"ccryptolib.internal.curve25519"local
sha512=require"ccryptolib.internal.sha512"local
random=require"ccryptolib.random"local
function
mask(sk)expect(1,sk,"string")lassert(#sk==32,"secret key length must be 32",2)local
mask=random.random(32)local
x=fq.decodeClamped(sk)local
r=fq.decodeClamped(mask)local
xr=fq.sub(x,r)return
fq.encode(xr)..mask
end
local
function
maskS(sk)expect(1,sk,"string")lassert(#sk==32,"secret key length must be 32",2)return
mask(sha512.digest(sk):sub(1,32))end
local
function
remask(msk)expect(1,msk,"string")lassert(#msk==64,"masked secret key length must be 64",2)local
newMask=random.random(32)local
xr=fq.decode(msk:sub(1,32))local
r=fq.decodeClamped(msk:sub(33))local
s=fq.decodeClamped(newMask)local
xs=fq.add(xr,fq.sub(r,s))return
fq.encode(xs)..newMask
end
local
function
ephemeralSk(msk)expect(1,msk,"string")lassert(#msk==64,"masked secret key length must be 64",2)return
msk:sub(33)end
local
function
hwExchangeOnPoint(sk,P)local
ok1,rP=hw.x25519Exchange(sk:sub(33),P)if
not
ok1
then
return
end
local
xr=fq.decode(sk:sub(1,32))local
r=fq.decodeClamped(sk:sub(33))local
x=fq.add(xr,r)local
ok2,xP=hw.x25519Exchange(fq.encodeClamped(x),P)if
not
ok2
then
return
end
return
true,xP,rP
end
local
function
exchangeOnPoint(sk,P)local
xr=fq.decode(sk:sub(1,32))local
r=fq.decodeClamped(sk:sub(33))local
rP,xrP,dP=c25.prac(P,fq.makeRuleset(fq.eighth(r),fq.eighth(xr)))if
not
rP
then
local
out=fp.encode(fp.num(0))return
out,out
end
local
xP=c25.dadd(dP,rP,xrP)local
Px,Pz=P[1],P[2]local
xPx,xPz=xP[1],xP[2]local
rPx,rPz=rP[1],rP[2]Px,Pz=fp.mul(Px,Pz),fp.square(Pz)xPx,xPz=fp.mul(xPx,xPz),fp.square(xPz)rPx,rPz=fp.mul(rPx,rPz),fp.square(rPz)local
Px2=fp.square(Px)local
Pz2=fp.square(Pz)local
Pxz=fp.mul(Px,Pz)local
APxz=fp.kmul(Pxz,486662)local
rhs=fp.mul(Px,fp.add(Px2,fp.carry(fp.add(APxz,Pz2))))local
root=fp.sqrtDiv(fp.num(1),fp.mul(fp.mul(xPz,rPz),rhs))if
not
root
then
local
out=fp.encode(fp.num(0))return
out,out
end
local
xPzrPzInv=fp.mul(fp.square(root),rhs)local
xPzInv=fp.mul(xPzrPzInv,rPz)local
rPzInv=fp.mul(xPzrPzInv,xPz)return
fp.encode(fp.mul(xPx,xPzInv)),fp.encode(fp.mul(rPx,rPzInv))end
local
G_ENC=fp.encode(fp.num(9))local
function
publicKey(msk)expect(1,msk,"string")lassert(#msk==64,"masked secret key length must be 64",2)local
ok,xP,rP=hwExchangeOnPoint(msk,G_ENC)if
ok
then
return
xP,rP
end
return(exchangeOnPoint(msk,c25.G))end
local
function
exchange(sk,pk)expect(1,sk,"string")lassert(#sk==64,"masked secret key length must be 64",2)expect(2,pk,"string")lassert(#pk==32,"public key length must be 32",2)local
ok,xP,rP=hwExchangeOnPoint(sk,pk)if
ok
then
return
xP,rP
end
return
exchangeOnPoint(sk,c25.decode(pk))end
return{mask=mask,remask=remask,publicKey=publicKey,ephemeralSk=ephemeralSk,exchange=exchange,}
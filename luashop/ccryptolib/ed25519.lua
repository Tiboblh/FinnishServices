local
expect=require"cc.expect".expect
local
lassert=require"ccryptolib.internal.util".lassert
local
hw=require"ccryptolib.internal.hw"local
fq=require"ccryptolib.internal.fq"local
sha512=require"ccryptolib.internal.sha512"local
ed=require"ccryptolib.internal.edwards25519"local
random=require"ccryptolib.random"local
function
publicKey(sk)expect(1,sk,"string")assert(#sk==32,"secret key length must be 32")local
ok,out=hw.ed25519PublicKey(sk)if
ok
then
return
out
end
local
h=sha512.digest(sk)local
x=fq.decodeClamped(h:sub(1,32))return
ed.encode(ed.mulG(fq.bits(x)))end
local
function
sign(sk,pk,msg)expect(1,sk,"string")lassert(#sk==32,"secret key length must be 32",2)expect(2,pk,"string")lassert(#pk==32,"public key length must be 32",2)expect(3,msg,"string")local
ok,out=hw.ed25519Sign(msg,sk)if
ok
then
return
out
end
local
h=sha512.digest(sk)local
x=fq.decodeClamped(h:sub(1,32))local
k=fq.decodeWide(random.random(64))local
r=ed.mulG(fq.bits(k))local
rStr=ed.encode(r)local
e=fq.decodeWide(sha512.digest(rStr..pk..msg))local
m=fq.decodeWide(random.random(64))local
s=fq.sub(fq.add(k,fq.mul(fq.add(x,m),e)),fq.mul(m,e))local
sStr=fq.encode(s)return
rStr..sStr
end
local
function
verify(pk,msg,sig)expect(1,pk,"string")lassert(#pk==32,"public key length must be 32",2)expect(2,msg,"string")expect(3,sig,"string")lassert(#sig==64,"signature length must be 64",2)local
ok,out=hw.ed25519Verify(msg,sig,pk)if
ok
then
return
out
end
local
y=ed.decode(pk)if
not
y
then
return
false
end
local
rStr=sig:sub(1,32)local
sStr=sig:sub(33)local
e=fq.decodeWide(sha512.digest(rStr..pk..msg))local
gs=ed.mulG(fq.bits(fq.decode(sStr)))local
ye=ed.mul(y,fq.bits(e))local
rv=ed.sub(gs,ed.niels(ye))return
ed.encode(rv)==rStr
end
return{publicKey=publicKey,sign=sign,verify=verify,}